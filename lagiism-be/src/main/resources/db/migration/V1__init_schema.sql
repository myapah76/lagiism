-- ==============================================================================

CREATE TABLE admin_accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(180) NOT NULL UNIQUE,
    full_name       VARCHAR(120) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    role            VARCHAR(32)  NOT NULL DEFAULT 'STAFF',
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at   TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_email     VARCHAR(180) NOT NULL,
    action          VARCHAR(80)  NOT NULL,
    target_type     VARCHAR(80)  NOT NULL,
    target_id       VARCHAR(120),
    details         TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_admin_audit_logs_created_at ON admin_audit_logs (created_at DESC);

CREATE TABLE password_reset_otps (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(180) NOT NULL,
    otp_hash        VARCHAR(255) NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    used            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_password_reset_otps_email ON password_reset_otps (email);

CREATE TABLE smtp_configs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host                VARCHAR(255) NOT NULL,
    port                INTEGER      NOT NULL DEFAULT 587,
    username            VARCHAR(255) NOT NULL,
    encrypted_password  TEXT         NOT NULL,
    from_email          VARCHAR(255) NOT NULL,
    from_name           VARCHAR(150) NOT NULL DEFAULT 'LAGIISM',
    use_tls             BOOLEAN      NOT NULL DEFAULT TRUE,
    use_ssl             BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled             BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cms_heroes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    headline              VARCHAR(200) NOT NULL,
    subheadline           VARCHAR(300) NOT NULL,
    badge_text            VARCHAR(120),
    primary_cta_label     VARCHAR(80)  NOT NULL DEFAULT 'EXPLORE DROP 01',
    secondary_cta_label   VARCHAR(80)  NOT NULL DEFAULT 'SHOP THE SET',
    image_url             TEXT         NOT NULL,
    image_public_id       VARCHAR(255),
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cms_sections (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_key       VARCHAR(80)  NOT NULL UNIQUE,
    title             VARCHAR(200) NOT NULL,
    subtitle          VARCHAR(300),
    content           TEXT,
    image_url         TEXT,
    image_public_id   VARCHAR(255),
    sort_order        INTEGER      NOT NULL DEFAULT 0,
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cms_reviews (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name       VARCHAR(120) NOT NULL,
    author_location   VARCHAR(120),
    rating            INTEGER      NOT NULL DEFAULT 5,
    comment           TEXT         NOT NULL,
    featured          BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order        INTEGER      NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE site_settings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key       VARCHAR(100) NOT NULL UNIQUE,
    setting_value     TEXT         NOT NULL,
    description       VARCHAR(255),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(40)  NOT NULL UNIQUE,
    title             VARCHAR(120) NOT NULL,
    subtitle          VARCHAR(200),
    image_url         TEXT,
    image_public_id   VARCHAR(255),
    sort_order        INTEGER      NOT NULL DEFAULT 0,
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE products (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                       VARCHAR(80)  NOT NULL UNIQUE,
    sku                        VARCHAR(60)  NOT NULL UNIQUE,
    name                       VARCHAR(180) NOT NULL,
    name_vi                    VARCHAR(180),
    price_vnd                  BIGINT       NOT NULL,
    category_code              VARCHAR(40)  NOT NULL,
    set_slot                   VARCHAR(20)  NOT NULL DEFAULT 'NONE',
    color_name                 VARCHAR(80)  NOT NULL,
    color_hex                  VARCHAR(16)  NOT NULL,
    sizes_csv                  VARCHAR(80)  NOT NULL DEFAULT 'S,M,L,XL',
    image_url                  TEXT         NOT NULL,
    image_public_id            VARCHAR(255),
    secondary_image_url        TEXT,
    secondary_image_public_id  VARCHAR(255),
    glb_model_slot             VARCHAR(255),
    description                TEXT,
    gsm                        VARCHAR(80),
    fabric                     VARCHAR(120),
    fit                        VARCHAR(120),
    origin                     VARCHAR(120),
    coordinates                VARCHAR(120),
    badge_text                 VARCHAR(60),
    active                     BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order                 INTEGER      NOT NULL DEFAULT 0,
    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_products_category_code ON products (category_code);
CREATE INDEX idx_products_active_sort ON products (active, sort_order);
