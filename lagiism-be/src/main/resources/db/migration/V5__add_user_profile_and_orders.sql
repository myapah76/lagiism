-- ==============================================================================
-- V5__add_user_profile_and_orders.sql
-- Adds default contact/shipping fields to users and creates orders/order_items
-- ==============================================================================

ALTER TABLE users ADD COLUMN phone VARCHAR(30);
ALTER TABLE users ADD COLUMN default_address TEXT;
ALTER TABLE users ADD COLUMN default_city VARCHAR(120);

CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code        VARCHAR(40)  NOT NULL UNIQUE,
    user_id           BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status            VARCHAR(32)  NOT NULL DEFAULT 'PENDING',
    total_vnd         BIGINT       NOT NULL,
    recipient_name    VARCHAR(120) NOT NULL,
    recipient_phone   VARCHAR(30)  NOT NULL,
    shipping_address  TEXT         NOT NULL,
    shipping_city     VARCHAR(120),
    note              TEXT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);

CREATE TABLE order_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT       NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_slug    VARCHAR(80)  NOT NULL,
    product_name    VARCHAR(180) NOT NULL,
    size            VARCHAR(16)  NOT NULL,
    color_name      VARCHAR(80),
    unit_price_vnd  BIGINT       NOT NULL,
    quantity        INTEGER      NOT NULL,
    image_url       TEXT
);
