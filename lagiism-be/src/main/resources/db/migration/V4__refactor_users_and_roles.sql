-- ==============================================================================
-- V4__refactor_users_and_roles.sql
-- Replaces admin_accounts with normalized users, roles, and user_roles tables
-- ==============================================================================

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(32)  NOT NULL UNIQUE,
    description VARCHAR(255)
);

INSERT INTO roles (name, description) VALUES
    ('USER',  'Standard storefront customer'),
    ('STAFF', 'Storefront staff with admin panel access'),
    ('ADMIN', 'Full system administrator');

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(180) NOT NULL UNIQUE,
    full_name       VARCHAR(120) NOT NULL,
    password_hash   VARCHAR(255),
    auth_provider   VARCHAR(32)  NOT NULL DEFAULT 'LOCAL',
    google_sub      VARCHAR(128) UNIQUE,
    avatar_url      TEXT,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at   TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

-- Migrate any existing rows from admin_accounts into users & user_roles
INSERT INTO users (id, email, full_name, password_hash, auth_provider, google_sub, avatar_url, active, last_login_at, created_at, updated_at)
SELECT id, email, full_name, password_hash, auth_provider, google_sub, avatar_url, active, last_login_at, created_at, updated_at
FROM admin_accounts;

INSERT INTO user_roles (user_id, role_id)
SELECT a.id, r.id
FROM admin_accounts a
JOIN roles r ON r.name = UPPER(a.role);

DROP TABLE admin_accounts;
